// TextWidth is the width in pixels of s drawn at scale.
func TextWidth(s string, scale int) int {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	return (n*4 - 1) * scale
}

// DrawText draws s with its top-left corner at (x, y).
func DrawText(dst *image.RGBA, x, y int, s string, c color.RGBA, scale int) {
	for _, r := range s {
		g, ok := glyphs[r]
		if !ok {
			g = glyphs['?']
		}
		for gy := 0; gy < 5; gy++ {
			for gx := 0; gx < 3; gx++ {
				if g[gy][gx] != '#' {
					continue
				}
				for sy := 0; sy < scale; sy++ {
					for sx := 0; sx < scale; sx++ {
						px, py := x+gx*scale+sx, y+gy*scale+sy
						if image.Pt(px, py).In(dst.Rect) {
							dst.SetRGBA(px, py, c)
						}
					}
				}
			}
		}
		x += 4 * scale
	}
}
